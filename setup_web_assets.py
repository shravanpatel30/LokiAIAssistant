"""Download the chat window's web libraries and fonts into web/vendor/ so the
window renders markdown, math and its fonts fully offline.

The files are already committed to the repo, so you normally never need
this. Run it only if web/vendor/ is missing or you want to update versions:

    python setup_web_assets.py
"""
import io
import re
import shutil
import tarfile
import urllib.request
from pathlib import Path

KATEX_VERSION = "0.16.11"
MARKED_VERSION = "12.0.2"      # pinned: marked v13+ changed its renderer API
FONTSOURCE_VERSION = "5.3.2"   # Google Sans fonts, packaged by fontsource.org (OFL-1.1)

# (npm package, family name used in chat.css, alphabets to keep)
FONTS = [
    ("@fontsource-variable/google-sans", "Google Sans", ("latin", "latin-ext", "greek")),
    ("@fontsource-variable/google-sans-code", "Google Sans Code", ("latin", "latin-ext")),
]

VENDOR = Path(__file__).parent / "web" / "vendor"


def _download_tarball(url):
    print(f"Downloading {url}")
    with urllib.request.urlopen(url, timeout=60) as r:
        return tarfile.open(fileobj=io.BytesIO(r.read()), mode="r:gz")


def _extract(tar, member_name, dest):
    data = tar.extractfile(member_name).read()
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_bytes(data)


def _get_katex():
    tar = _download_tarball(f"https://registry.npmjs.org/katex/-/katex-{KATEX_VERSION}.tgz")
    katex_dir = VENDOR / "katex"
    for m in tar.getmembers():
        name = m.name
        if name in ("package/dist/katex.min.js", "package/dist/katex.min.css"):
            _extract(tar, name, katex_dir / Path(name).name)
        elif name.startswith("package/dist/fonts/") and name.endswith(".woff2"):
            _extract(tar, name, katex_dir / "fonts" / Path(name).name)


def _get_marked():
    tar = _download_tarball(f"https://registry.npmjs.org/marked/-/marked-{MARKED_VERSION}.tgz")
    _extract(tar, "package/marked.min.js", VENDOR / "marked.min.js")


def _get_fonts():
    """Keep only the alphabets we need and write web/vendor/fonts/fonts.css."""
    fonts_dir = VENDOR / "fonts"
    css_out = []
    for package, family, subsets in FONTS:
        short = package.split("/")[1]
        tar = _download_tarball(
            f"https://registry.npmjs.org/{package}/-/{short}-{FONTSOURCE_VERSION}.tgz"
        )
        for css_name in ("package/wght.css", "package/wght-italic.css"):
            css = tar.extractfile(css_name).read().decode("utf-8")
            # Each block looks like:  /* google-sans-latin-wght-normal */ @font-face {...}
            for comment, block in re.findall(r"/\* ([\w-]+) \*/\s*(@font-face \{.*?\})", css, re.S):
                subset = comment[len(short) + 1:].rsplit("-wght-", 1)[0]
                if subset not in subsets:
                    continue
                filename = re.search(r"url\(\./files/([^)]+)\)", block).group(1)
                _extract(tar, f"package/files/{filename}", fonts_dir / filename)
                block = re.sub(r"font-family: '[^']+'", f"font-family: '{family}'", block)
                block = block.replace("./files/", "./")
                css_out.append(f"/* {comment} */\n{block}")
    (fonts_dir / "fonts.css").write_text(
        "/* Generated by setup_web_assets.py — Google Sans fonts, SIL Open Font License 1.1 */\n\n"
        + "\n\n".join(css_out) + "\n",
        encoding="utf-8",
    )
    return len(css_out)


def main():
    if VENDOR.exists():
        shutil.rmtree(VENDOR)
    _get_katex()
    _get_marked()
    n_faces = _get_fonts()
    print(f"Done. KaTeX {KATEX_VERSION}, marked {MARKED_VERSION} and "
          f"{n_faces} Google Sans font files saved to {VENDOR}")


if __name__ == "__main__":
    main()
